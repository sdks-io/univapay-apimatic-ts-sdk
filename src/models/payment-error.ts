import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";

/**
 * リソース処理中（課金や返金など）に発生した決済エラー。HTTP ステータスは成功（2xx）を返しますが、リソースの `status` は `failed`
 * になり、このオブジェクトにデータが投入されます。
 */
export type PaymentError = {
  /**
   * 決済エラーコード。
   *
   * | コード | 説明 |
   * | :--- | :--- |
   * | 301 | カード番号エラー。 |
   * | 302 | 無効な有効期限（月）。 |
   * | 303 | 無効な有効期限（年）。 |
   * | 304 | カードの有効期限切れ。 |
   * | 305 | セキュリティコード（CVV）エラー。 |
   * | 306 | カード拒否（オーソリ審査エラー）。 |
   * | 307 | 無効なカード。 |
   * | 308 | このカードはカード会社によって承認されていません。 |
   * | 309 | 一般的なエラーが発生しました。詳細はダッシュボードで確認できます。 |
   * | 310 | 無効な消費者データ（無効なリクエストデータ）。 |
   * | 311 | 短期間に同じカードでの課金が多すぎます。しばらく待ってからもう一度お試しください。 |
   * | 312 | この課金はキャンセルできません。 |
   * | 313 | オーソリの有効期限切れ（課金のキャプチャ中）。 |
   * | 314 | このカードはイシュアによって紛失届が出されているか、無効化されています。 |
   * | 315 | カード発行会社にお問い合わせください。 |
   * | 316 | カード名義人の姓が必要です。 |
   * | 317 | 部分キャプチャはサポートされていません。 |
   * | 318 | 部分返金はサポートされていません。 |
   * | 319 | 不正の疑い（セキュリティ制限）。 |
   * | 320 | 銀行のシステムでエラーが発生しました。 |
   * | 321 | 動的ディスクリプタ（利用明細書表記の動的変更）はサポートされていません。 |
   * | 322 | バーコード/QR コードが無効です。 |
   * | 323 | バーコード/QR コードの有効期限が切れています。 |
   * | 324 | このバーコード/QR コードはすでに処理されています。 |
   * | 325 | このバーコード/QR コードは現在処理中です。 |
   * | 326 | 高リスクプロファイルのため拒否されました。 |
   * | 327 | 支払い期限（5分間のタイムアウト）が切れました。 |
   * | 328 | リカバリに失敗しました。手動での介入が必要です。 |
   * | 329 | 返金に失敗しました。 |
   * | 330 | 残高不足。 |
   * | 331 | メタデータフィールドの値が無効、または欠落しています。 |
   * | 332 | クロスボーダートランザクションが許可されていません：ID が不足しています。 |
   * | 333 | クロスボーダートランザクションが許可されていません：電話番号が不足しています。 |
   * | 334 | クロスボーダートランザクションが許可されていません：未許可の決済手段です。 |
   * | 335 | クロスボーダートランザクションが許可されていません：氏名が不足しています。 |
   * | 336 | この決済手段の支払い上限を超えました。 |
   * | 337 | この加盟店の支払い上限を超えました。 |
   * | 338 | 決済情報が見つかりません。 |
   * | 339 | 重複した決済情報です。 |
   * | 340 | この消費者の小売 QR アカウントはゲートウェイによって拒否されました。 |
   * | 341 | この加盟店には、このゲートウェイに必要な情報が不足しています。 |
   * | 342 | クロスボーダートランザクションが許可されていません：未許可の通貨です。 |
   * | 343 | ゲートウェイのサーバーエラーのため、決済を処理できませんでした。 |
   * | 344 | 選択された決済手段は、ゲートウェイ側で一時的に利用できません。 |
   * | 345 | 決済はすでにキャンセルされています。 |
   * | 346 | システム遅延により決済処理がタイムアウトし、キャンセルされました。 |
   * | 351 | 無効なトランザクション。 |
   * | 355 | カードが指定された支払い区分（分割払いなど）をサポートしていません。 |
   * | 356 | カードが3Dセキュアに登録されていません。 |
   * | 358 | 3Dセキュア認証に失敗しました（消費者の理由：パスワード間違いなど）。 |
   * | 359 | 3Dセキュア認証に失敗しました（カード会社の理由）。 |
   * | 500 | リクエスト実行前の前処理中にエラーが発生しました。 |
   * | 501 | 内部エラーが発生しました。サポートにお問い合わせください。 |
   * | 502 | レスポンスを待つ間にリクエストがタイムアウトしました。 |
   * | 601 | このサービスでシステムリリースエラーが発生しました。詳細を確認してください。 |
   * | 602 | 決済プロセッサが送信されたリクエストを拒否しました。詳細を確認してください。 |
   * | 603 | 送信された消費者本人確認が税関によって拒否されました。 |
   * | 604 | 必要な消費者 ID 情報が加盟店から送信されませんでした。 |
   */
  code?: number;
  /** 決済が失敗した理由を説明する短いメッセージ。 */
  message?: string;
  /** 利用可能な場合、決済失敗に関するさらに具体的な詳細。 */
  detail?: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const paymentErrorSchema: Schema<PaymentError> = s.object<PaymentError>(
  {
    code: s.optional(s.int()),
    message: s.optional(s.string()),
    detail: s.optional(s.string()),
  },
  { additionalProperties: s.json() },
);
